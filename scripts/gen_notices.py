"""Regenerates THIRD_PARTY_NOTICES.md from the dependencies' own license files.

Run from the repo root after changing dependencies: python scripts/gen_notices.py
Needs the submodules checked out, abseil fetched (scripts\\build.cmd does that), and cargo.
"""
import glob
import os
import shutil
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def read(*parts):
    with open(os.path.join(ROOT, *parts), encoding="utf-8") as f:
        return f.read().strip()


def rust_crates():
    cargo = shutil.which("cargo") or os.path.expanduser(r"~\.cargo\bin\cargo.exe")
    out = subprocess.run(
        [cargo, "tree", "--locked", "-e", "normal", "--prefix", "none", "--format", "{p}|{l}"],
        cwd=os.path.join(ROOT, "native", "dfshim"), capture_output=True, text=True, check=True,
    ).stdout
    crates = set()
    for line in out.splitlines():
        name, _, lic = line.partition("|")
        name = name.replace(" (proc-macro)", "").split(" (")[0].strip()
        lic = lic.replace(" (*)", "").strip()
        if name.startswith("dfshim ") or not lic:
            continue
        crates.add((name, lic))
    return sorted(crates)


abseil = glob.glob(os.path.join(ROOT, "subprojects", "webrtc-audio-processing", "subprojects", "abseil-cpp-*", "LICENSE"))
if not abseil:
    raise SystemExit("abseil not fetched yet; run scripts\\build.cmd first")

